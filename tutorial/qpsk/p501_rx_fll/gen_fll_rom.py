#!/usr/bin/env python3
"""Writes rtl/qpsk_fll_taps.v: the 55 complex band-edge taps (the upper filter, Q17; the lower filter is the complex conjugate) from the same numbers as the integer model."""
import os
import numpy as np
import qpsk_fll_fixed as M
rtl = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "rtl", "qpsk_fll_taps.v")
s16 = lambda v: "16'sd%d" % v if v >= 0 else "-16'sd%d" % (-v)
with open(rtl, "w") as f:
    f.write("// Generated by tutorial/qpsk/p501_rx_fll/gen_fll_rom.py - do not edit.\n// The 55 complex taps of GNU Radio's fll_band_edge_cc (samples per symbol 4, roll-off 0.35), upper filter, Q%d; the lower filter is the conjugate.\n" % M.TAP_Q)
    f.write("`timescale 1ns/1ps\nmodule qpsk_fll_taps (\n  input  wire        clk,\n  input  wire [5:0]  i,\n  output reg  signed [15:0] cr,\n  output reg  signed [15:0] ci\n);\n  always @(posedge clk) begin\n    case (i)\n")
    for k in range(M.NTAPS):
        f.write("      6'd%d: begin cr <= %s; ci <= %s; end\n" % (k, s16(int(M.TAP_R[k])), s16(int(M.TAP_I[k]))))
    f.write("      default: begin cr <= 16'sd0; ci <= 16'sd0; end\n    endcase\n  end\nendmodule\n")
print("wrote", os.path.normpath(rtl), " max |tap| %d (16-bit signed range ok: %s)" % (max(abs(M.TAP_R).max(), abs(M.TAP_I).max()), max(abs(M.TAP_R).max(), abs(M.TAP_I).max()) < 32768))
