#!/usr/bin/env python3
"""Generates rtl/qpsk_rx_rom.v (matched and derivative filter coefficients, 16 arms x 44 taps) and rtl/qpsk_rx_trig.v (1024-entry cosine/sine table, Q15)
from the same numbers as the fixed-point model qpsk_rx_fixed.py."""
import os, numpy as np
from qpsk_rx_fixed import coefs, cos_sin_lut, NF, NTAPS

here = os.path.dirname(os.path.abspath(__file__)); rtl = os.path.join(here, "..", "..", "..", "rtl")
cm, cd = coefs()
def s16(v): return "16'sd%d" % v if v >= 0 else "-16'sd%d" % (-v)
with open(os.path.join(rtl, "qpsk_rx_rom.v"), "w") as f:
    f.write("// Generated by tutorial/qpsk/p501_rx/gen_rx_rom.py - do not edit.\n// Polyphase matched filter (cm) and derivative filter (cd): %d arms x %d taps, int16 (x 2^15). Address = {arm[3:0], tap[5:0]}; taps 44..63 are 0.\n" % (NF, NTAPS))
    f.write("`timescale 1ns/1ps\nmodule qpsk_rx_rom (\n  input  wire        clk,\n  input  wire [9:0]  addr,\n  output reg  [15:0] cm,\n  output reg  [15:0] cd\n);\n  always @(posedge clk) begin\n    case (addr)\n")
    for k in range(NF):
        for i in range(64):
            a = (k << 6) | i; m = int(cm[k][i]) if i < NTAPS else 0; d = int(cd[k][i]) if i < NTAPS else 0
            f.write("      10'd%d: begin cm <= %s; cd <= %s; end\n" % (a, s16(m), s16(d)))
    f.write("      default: begin cm <= 16'sd0; cd <= 16'sd0; end\n    endcase\n  end\nendmodule\n")
c, s = cos_sin_lut()
with open(os.path.join(rtl, "qpsk_rx_trig.v"), "w") as f:
    f.write("// Generated by tutorial/qpsk/p501_rx/gen_rx_rom.py - do not edit.\n// cos / sin of 2*pi*a/1024, Q15 (+-32767).\n`timescale 1ns/1ps\nmodule qpsk_rx_trig (\n  input  wire        clk,\n  input  wire [9:0]  a,\n  output reg  [15:0] c,\n  output reg  [15:0] s\n);\n  always @(posedge clk) begin\n    case (a)\n")
    for k in range(1024):
        f.write("      10'd%d: begin c <= %s; s <= %s; end\n" % (k, s16(int(c[k])), s16(int(s[k]))))
    f.write("      default: begin c <= 16'sd32767; s <= 16'sd0; end\n    endcase\n  end\nendmodule\n")
print("wrote qpsk_rx_rom.v and qpsk_rx_trig.v")
