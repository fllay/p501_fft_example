#!/usr/bin/env python3
"""Bit-exact NumPy model of the FPGA QPSK transmitter (rtl/qpsk_tx.v) and generator of its coefficient ROM (rtl/qpsk_rrc_coef.v).

    python3 qpsk_model.py            # prints the design numbers and (re)writes ../../../rtl/qpsk_rrc_coef.v

The transmitter, in the order of GNU Radio's `digital.generic_mod` (differential QPSK, constellation_dqpsk):
  PRBS-15 bits (x^15 + x^14 + 1, seed 0x7FFF, first bit = s[14]) -> 2-bit chunks, first bit = MSB -> pre-differential map [0,1,3,2]
  -> differential encoder d = (d + m) mod 4 -> point index d -> (I, Q) = (+,+), (-,+), (-,-), (+,-) -> RRC pulse, 4 samples per symbol
  -> x amplitude (Q15) -> 16-bit samples.
The RRC filter is a polyphase FIR of 45 taps (roll-off 0.35, 11 symbols); the symbols are +-1, so it needs only additions."""
import numpy as np, os, sys

SPS, BETA, SPAN = 4, 0.35, 11
NT = SPS * SPAN + 1                 # 45 taps
COEF_SCALE = 12288.0                # tap value 1.0 (the peak) = 12288: the largest per-phase sum of |taps| (about 17800) still fits in 16 signed bits
PRE_DIFF = [0, 1, 3, 2]
SIGN_I = [+1, -1, -1, +1]           # constellation_dqpsk points: (+,+), (-,+), (-,-), (+,-)
SIGN_Q = [+1, +1, -1, -1]


def rrc_taps(beta=BETA, sps=SPS, ntaps=NT):
    k = (np.arange(ntaps) - (ntaps - 1) / 2) / sps          # time in symbols
    h = np.zeros(ntaps)
    for n, t in enumerate(k):
        if abs(t) < 1e-12: h[n] = 1 + beta * (4 / np.pi - 1)
        elif abs(abs(t) - 1 / (4 * beta)) < 1e-9: h[n] = beta / np.sqrt(2) * ((1 + 2 / np.pi) * np.sin(np.pi / (4 * beta)) + (1 - 2 / np.pi) * np.cos(np.pi / (4 * beta)))
        else: h[n] = (np.sin(np.pi * t * (1 - beta)) + 4 * beta * t * np.cos(np.pi * t * (1 + beta))) / (np.pi * t * (1 - (4 * beta * t) ** 2))
    return h / h.max()


def coef_int():
    return np.round(rrc_taps() * COEF_SCALE).astype(int)       # 45 integers, peak 4096


def prbs15_bits(n, state=0x7FFF):
    out = np.zeros(n, dtype=np.uint8)
    for i in range(n):
        out[i] = (state >> 14) & 1
        state = ((state << 1) & 0x7FFF) | (((state >> 14) ^ (state >> 13)) & 1)
    return out


def symbol_indices(bits):
    """bits -> DQPSK point indices (GNU Radio generic_mod order)."""
    chunks = bits[0::2].astype(int) * 2 + bits[1::2].astype(int)
    d, out = 0, np.zeros(len(chunks), dtype=int)
    for n, c in enumerate(chunks):
        d = (d + PRE_DIFF[c]) % 4; out[n] = d
    return out


def model(n_samples, amp=0x4000, bits=None):
    """The transmitter's output at the sample rate (ce rate): two int arrays (I, Q) of n_samples, including the one-sample pipeline latency
    (the first sample is 0) and the initial history of +1 symbols that the hardware starts with."""
    h = coef_int(); nsym = n_samples // SPS + SPAN + 2
    if bits is None: bits = prbs15_bits(2 * nsym)
    idx = symbol_indices(bits)
    si = np.array([SIGN_I[i] for i in idx]); sq = np.array([SIGN_Q[i] for i in idx])
    hi = np.concatenate([np.ones(SPAN), si]); hq = np.concatenate([np.ones(SPAN), sq])     # history starts as all +1
    ysum_i = np.zeros(n_samples, dtype=np.int64); ysum_q = np.zeros(n_samples, dtype=np.int64)
    for n in range(n_samples):
        m, p = divmod(n, SPS)                          # symbol m enters the history before its first sample (p = 0)
        for j in range(SPAN + 1):
            t = SPS * j + p
            if t < NT:
                ysum_i[n] += h[t] * hi[SPAN + m - j]; ysum_q[n] += h[t] * hq[SPAN + m - j]
    def stage(y):
        v = (y * int(amp)) >> 15                       # arithmetic shift (floor), as in the RTL
        return np.clip(v, -32768, 32767)
    oi, oq = stage(ysum_i), stage(ysum_q)
    # the output register after sample k holds the scaled sum of sample k-1 (stage 1: sum, stage 2: scale): one sample of latency
    return np.concatenate([[0], oi[:-1]]).astype(int), np.concatenate([[0], oq[:-1]]).astype(int)


def write_rom(path):
    h = coef_int(); lines = []
    lines.append("// Generated by tutorial/qpsk/p501_tx/qpsk_model.py - do not edit.\n// RRC pulse, roll-off %.2f, %d samples per symbol, %d taps, peak tap = %d. Output: the 12 taps h[4j+ph] of a polyphase phase (0 where 4j+ph >= %d).\n" % (BETA, SPS, NT, int(COEF_SCALE), NT))
    lines.append("`timescale 1ns/1ps\nmodule qpsk_rrc_coef (\n  input  wire [1:0]     ph,\n  output reg  [%d:0]   h       // 12 coefficients, 16 bit signed each, j = 0 in the lowest bits\n);\n" % (16 * (SPAN + 1) - 1))
    lines.append("  always @* begin\n    case (ph)\n")
    for p in range(SPS):
        taps = [int(h[SPS * j + p]) if SPS * j + p < NT else 0 for j in range(SPAN + 1)]
        packed = " , ".join("16'sd%d" % v if v >= 0 else "-16'sd%d" % (-v) for v in reversed(taps))
        lines.append("      2'd%d: h = {%s};\n" % (p, packed))
    lines.append("    endcase\n  end\nendmodule\n")
    open(path, "w").write("".join(lines))


if __name__ == "__main__":
    h = coef_int(); print("taps:", NT, " peak", h.max(), " sum|h| per phase:", [int(sum(abs(h[p::SPS]))) for p in range(SPS)], " sum h^2 (all taps): %.0f" % float(np.sum(h.astype(float) ** 2)))
    oi, oq = model(20000, amp=0x7FFF)
    r = np.sqrt(np.mean(oi[100:].astype(float) ** 2 + oq[100:].astype(float) ** 2))
    print("amp = 0x7FFF: complex rms %.0f (%.2f of full scale), peak |I| %d |Q| %d" % (r, r / 32768, abs(oi).max(), abs(oq).max()))
    here = os.path.dirname(os.path.abspath(__file__)); rom = os.path.join(here, "..", "..", "..", "rtl", "qpsk_rrc_coef.v")
    write_rom(rom); print("wrote", os.path.normpath(rom))
