#!/usr/bin/env python3
"""Bit-exact model of the FPGA 16-QAM frame transmitter (rtl/qam16_tx_fr.v), and the generator of its symbol table (rtl/qam16_tx_zc.v).

    python3 qam16_tx_model.py            # (re)writes ../../rtl/qam16_tx_zc.v and prints the design numbers

Frame (967 symbols, as frame16.py): CP 8 | ZC 63 | 14 x (63 16-QAM + 1 pilot). Symbol values are integers in units of 1/64 of a 16-QAM level: the levels are +-64 and +-192 (Gray, as the receiver), the pilot is +-PA and the ZC word is PA x ZC[k]
with PA = round(64 sqrt(10)) = 202 (unit RMS = 64 sqrt(10)). The payload is the PRBS-15 (x^15 + x^14 + 1, seed 0x7FFF, MSB first, 4 bits per symbol, I = the first two bits, Q = the last two), restarted at its first symbol in every frame.
Pulse shaping: the polyphase RRC FIR of qpsk_tx.v (45 taps, 12 per phase, rtl/qpsk_rrc_coef.v), but with multipliers because the symbols are not +-1:
    ysum[n] = (sum_j h[4j + ph] s[m - j] + 32) >> 6   (m = n // 4, ph = n % 4, s = 0 before the first symbol), registered;  dac[n] = clip((ysum[n-1] x amp) >> 15, +-32767)   (amp Q15; dac[0] = 0)
"""
import os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "..", "qpsk", "p501_tx"))
import frame16 as F
import qam_zc_fixed as Z
from qpsk_model import coef_int

PA = int(round(64 * np.sqrt(10)))                    # 202
LEV = {0: -192, 1: -64, 2: 192, 3: 64}               # 2-bit index -> level x 64
SPS, NH = 4, 12


def zc_table():
    """ZC[k] x PA, rounded: (zr, zi) per k = 0..62 (ZC = (QR, -QI) in Q14)"""
    zr = [int((int(Z.QR[k]) * PA + 8192) >> 14) for k in range(63)]
    zi = [int((-int(Z.QI[k]) * PA + 8192) >> 14) for k in range(63)]
    return zr, zi


def frame_symbols(nfr):
    """the symbols (si, sq) of nfr frames, integers"""
    zr, zi = zc_table(); ref = F.prbs15_indices()
    out = []
    for _ in range(nfr):
        for q in range(F.FRAME):
            if q < 8: out.append((zr[55 + q], zi[55 + q]))
            elif q < 71: out.append((zr[q - 8], zi[q - 8]))
            else:
                o = q - 71; b, r = divmod(o, F.BLK)
                if r == F.BLK - 1: out.append((PA if F.PILOTS[b] > 0 else -PA, 0))
                else:
                    ix = int(ref[b * F.N_DATA + r]); out.append((LEV[ix >> 2], LEV[ix & 3]))
    return out


def model(n_samples, amp=0x2000, nfr=None):
    """(dac_i, dac_q) int arrays of n_samples samples"""
    nsym = n_samples // SPS + 2
    nfr = nfr or (nsym // F.FRAME + 2)
    sym = np.array(frame_symbols(nfr), dtype=np.int64)
    h = coef_int()
    hp = np.zeros((SPS, NH), dtype=np.int64)
    for ph in range(SPS):
        for j in range(NH):
            if SPS * j + ph < len(h): hp[ph, j] = h[SPS * j + ph]
    ys = np.zeros((2, n_samples), dtype=np.int64)
    for n in range(n_samples):
        m, ph = divmod(n, SPS)
        for c in range(2):
            acc = 0
            for j in range(NH):
                if m - j >= 0: acc += int(hp[ph, j]) * int(sym[m - j, c])
            ys[c, n] = (acc + 32) >> 6
    dac = np.zeros((2, n_samples), dtype=np.int64)
    for c in range(2):
        for n in range(1, n_samples):
            dac[c, n] = max(-32767, min(32767, (int(ys[c, n - 1]) * amp) >> 15))
    return dac[0], dac[1]


def write_rom():
    zr, zi = zc_table()
    lines = ["// Generated by tutorial/qam16/qam16_tx_model.py - do not edit.",
             "// ZC[k] x PA (PA = 202 = 64 sqrt(10)), rounded, k = 0..62: the Zadoff-Chu word of the 16-QAM frame in the transmitter's symbol units (combinational).",
             "`timescale 1ns/1ps", "module qam16_tx_zc (", "  input  wire [5:0] k,", "  output reg  signed [9:0] zr,", "  output reg  signed [9:0] zi", ");", "  always @* begin", "    case (k)"]
    for k in range(63): lines.append("      6'd%d: begin zr = %d; zi = %d; end" % (k, zr[k], zi[k]))
    lines += ["      default: begin zr = 0; zi = 0; end", "    endcase", "  end", "endmodule", ""]
    path = os.path.join(HERE, "..", "..", "rtl", "qam16_tx_zc.v")
    open(path, "w").write("\n".join(lines)); return os.path.normpath(path)


if __name__ == "__main__":
    print("wrote", write_rom())
    i, q = model(8000, 0x2000)
    print("amp 0.25: first samples", i[:12], "peak %d rms %.0f" % (np.max(np.abs(i)), np.sqrt(np.mean(i[2000:].astype(float) ** 2))))
