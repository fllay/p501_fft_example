#!/usr/bin/env python3
"""Writes rtl/qam_zc_rom.v: conj(ZC[k]) = exp(+j pi k (k+1) / 63) in Q14 (k = 0..62), registered output (one clock).   python3 gen_zc_rom.py"""
import os
import qam_zc_fixed as Z

out = ["// Generated by tutorial/qam16/gen_zc_rom.py - do not edit.",
       "// conj(ZC[k]) = exp(+j pi k (k+1) / 63), Q14, k = 0..62 (the Zadoff-Chu word, root 1, 63rd roots of unity). The known word symbols ZC[k] of the PLL are (qr, -qi).",
       "`timescale 1ns/1ps", "module qam_zc_rom (", "  input  wire        clk,", "  input  wire [5:0]  addr,", "  output reg  signed [15:0] qr,", "  output reg  signed [15:0] qi", ");",
       "  always @(posedge clk) begin", "    case (addr)"]
for k in range(63):
    out.append("      6'd%d: begin qr <= %d; qi <= %d; end" % (k, Z.QR[k], Z.QI[k]))
out += ["      default: begin qr <= 16'sd0; qi <= 16'sd0; end", "    endcase", "  end", "endmodule", ""]
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "rtl", "qam_zc_rom.v")
open(path, "w").write("\n".join(out).replace("<= -", "<= -"))
print("wrote", os.path.normpath(path))
